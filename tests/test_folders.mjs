import assert from 'node:assert/strict';
import {createFolders} from '../web/folders.js';
const elements=new Map();
globalThis.document={getElementById(id){if(!elements.has(id))elements.set(id,{value:'',textContent:'',disabled:false,replaceChildren(){},getClientRects(){return [];}});return elements.get(id);}};
const el=id=>document.getElementById(id);
let state={models:'/기존 모델',busy:false,problem:'',ready:{speech:true,voices:true,context:true}},fail=false,applied=0,requests=[],selected='';
const folders=createFolders({api:async(action,data)=>{requests.push({action,data});if(action==='pick-path')return {path:selected};if(fail)throw Error('경로 확인 실패');if(action==='model-folder')state={...state,models:data.path};return state;},onApplied:async()=>{applied++;}});
folders.set(state);
assert.equal(el('model-root').value,'/기존 모델');assert.equal(el('apply-model-folder').disabled,false);
await el('model-folder-form').onsubmit({preventDefault(){}});
assert.equal(requests.at(-1).action,'pick-path');assert.equal(applied,0);assert.equal(el('model-root').value,'/기존 모델');
selected='/새 폴더';
fail=true;await el('model-folder-form').onsubmit({preventDefault(){}});
assert.match(el('model-folder-notice').textContent,/실패/);assert.equal(applied,0);assert.match(el('model-folder-current').textContent,/기존 모델/);
assert.equal(el('model-root').value,'/기존 모델');
fail=false;await el('model-folder-form').onsubmit({preventDefault(){}});
assert.equal(applied,1);assert.equal(el('apply-model-folder').disabled,false);assert.match(el('model-folder-current').textContent,/새 폴더/);
await el('model-folder-form').onsubmit({preventDefault(){}});assert.equal(applied,1);
folders.set({...state,busy:true});const count=requests.length;
await el('model-folder-form').onsubmit({preventDefault(){}});
assert.equal(requests.length,count);assert.equal(el('model-root').disabled,true);
folders.set({...state,busy:false,problem:'드라이브 연결 필요'});assert.match(el('model-folder-state').textContent,/연결 필요/);
console.log('폴더 선택·취소·실패 시 이전 경로 유지·적용·작업 중 차단 검사 통과');
