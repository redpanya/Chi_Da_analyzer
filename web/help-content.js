export function getHelpContent(id, read) {
  const entry = content[id];
  if (!entry) return {title: '도움말', paragraphs: ['도움말을 불러오지 못했습니다. 화면을 새로고침한 뒤 다시 확인하세요.']};
  if(id==='voice-model') {
    const data=read('voices-model','dataset')||{};
    const guide=voiceModelHelp(read('voices-backend','value'),{ready:data.ready==='true',engine:data.engine==='true',supported:data.supported!=='false'});
    return {...entry,...guide,current:`현재 엔진: ${read('voices-backend')} · ${guide.status}`};
  }
  const values = {
    'speech-options': () => `현재 발화 검출: ${read('speech-vad')} · 용어 힌트 ${read('speech-prompt', 'length')}자`,
    'speech-model': () => `현재 언어: ${read('speech-language')}`,
    'voice-run': () => `현재 화자 수: ${read('voices-number')} (0 = 자동)`,
    'context': () => `새 정리 설정: Gemma 4 E4B · 사고 ${read('context-thinking', 'checked') ? '켜기' : '끄기'}`,
    'explore-offset': () => `현재 입력: ${read('explore-offset')}초 · 보정 적용 후 사용`,
    'context-offset': () => `새 정리 보정값: ${read('context-offset')}초`,
  };
  return {...entry, current: values[id]?.()};
}
